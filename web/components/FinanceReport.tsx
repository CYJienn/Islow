"use client";
import { useState } from "react";

type Snapshot = { report_id: string; batch_results: Record<string, unknown>; summary?: unknown; warnings: string[]; status: string };
// Keep the selected snapshot in memory for this tab; never persist invoice data in browser storage.
let attached: Snapshot | null = null;
export function financeReportPayload() {
  return attached ? { finance: { mode: "configured", report: attached } } : {};
}

export default function FinanceReport() {
  const [label, setLabel] = useState(attached?.report_id || "");
  const [error, setError] = useState("");
  return <div className="finance-report">
    <label>Finance report (.json)
      <input type="file" accept=".json,application/json" aria-label="Attach finance report" onChange={async (event) => {
        const file = event.target.files?.[0];
        if (!file) return;
        try {
          if (file.size > 10_000_000) throw new Error("Report file exceeds 10 MB.");
          const data = JSON.parse(await file.text());
          if (typeof data.report_id !== "string" || !data.batch_results || typeof data.batch_results !== "object")
            throw new Error("Choose report.json generated by Invoice Assurance.");
          const batch = data.batch_results;
          const snapshot: Snapshot = {
            report_id: data.report_id, status: "partial", summary: data.summary,
            batch_results: Object.fromEntries(["checked", "valid_reference_matches", "invalid_reference_matches", "fully_verified", "supplied_suspected_exposure", "test_suspected_exposure", "confirmed_fraud", "exposure_method"].map(key => [key, batch[key]])),
            warnings: ["User-attached report snapshot; not a fresh analysis.", "Invoice details omitted from this discussion preview."]
          };
          if (JSON.stringify(snapshot).length > 35000) throw new Error("Report summary is too large.");
          attached = snapshot; setLabel(snapshot.report_id); setError("");
        } catch (cause) { attached = null; setLabel(""); setError(cause instanceof Error ? cause.message : "Cannot read report."); }
      }} />
    </label>
    <p className="session-hint">{label ? `Attached ${label}. Its summary will be sent to the backend and AI when you start a discussion.` : "Attach the generated report.json to discuss invoice findings and suspected exposure."}</p>
    {label && <button type="button" onClick={() => { attached = null; setLabel(""); }}>Remove report</button>}
    {error && <p role="alert">{error}</p>}
  </div>;
}
